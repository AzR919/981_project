"""
Analysis of v3e (T15: threshold in class share), implementing extra/analysis/review/PREREG_v3d_addendum1.md.

usage:
    python extra/experiments/analyze_v3e.py [--raw ~/rlvr-data/v3e] [--out extra/analysis/v3e]

Class A is answer class 0 (share m); class B is the other K - 1 classes. R = -Delta_B(A) / Delta_B(B) at
step 0; m* is where the median Delta_B(mixed) crosses zero (linear interpolation in logit m).
"""

import argparse
import glob
import gzip
import json
import os
import sys
from multiprocessing import Pool

import numpy as np
import pandas as pd

sys.path[:0] = [os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),  # repo root
                 os.path.dirname(os.path.dirname(os.path.abspath(__file__)))]  # extra/

from experiments.analyze import markdown  # noqa: E402
from experiments.analyze_v3 import t1_labels  # noqa: E402

TAU = 1e-3


def read_one(path):
    with gzip.open(path, "rt") as f:
        d = json.load(f)
    cfg = d["config"]
    cls, _ = t1_labels(cfg)
    p0, tail = np.asarray(d["p_init"]), np.asarray(d["tail_max"])
    absorbed = (tail < TAU) & (p0 >= 10 * TAU)
    b = d["branches"]["0"]
    return dict(K=cfg["K"], arch=cfg["arch"], rho=cfg["rho"], m=cfg["majority"], task_seed=cfg["task_seed"],
                share_a=float((cls == 0).mean()), d_b_a=b["d_b_a"], d_b_b=b["d_b_b"], d_b_mixed=b["d_b_mixed"],
                d_a_mixed=b["d_a_mixed"], absorbed_b=float(absorbed[cls != 0].mean()),
                absorbed_a=float(absorbed[cls == 0].mean()))


def logit(x):
    return np.log(x / (1 - x))


def crossing(m, y):
    """m where y changes from positive to negative, interpolated linearly in logit m; nan if it never does."""
    for i in range(len(m) - 1):
        if y[i] > 0 >= y[i + 1]:
            z = logit(m[i]) + (logit(m[i + 1]) - logit(m[i])) * y[i] / (y[i] - y[i + 1])
            return float(1 / (1 + np.exp(-z)))
    return np.nan


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw", default=os.path.expanduser("~/rlvr-data/v3e"))
    parser.add_argument("--out", default="extra/analysis/v3e")
    parser.add_argument("--jobs", type=int, default=10)
    args = parser.parse_args()
    cache = os.path.join(args.raw, "cache", "runs.csv")
    if not os.path.exists(cache):
        paths = sorted(glob.glob(os.path.join(args.raw, "*", "results", "*", "*.json.gz")))
        with Pool(args.jobs) as pool:
            rows = pool.map(read_one, paths, chunksize=8)
        os.makedirs(os.path.dirname(cache), exist_ok=True)
        pd.DataFrame(rows).to_csv(cache, index=False)
    runs = pd.read_csv(cache)
    runs["R"] = -runs.d_b_a / runs.d_b_b
    os.makedirs(args.out, exist_ok=True)

    per_m = runs.groupby(["K", "arch", "rho", "m"]).agg(
        tasks=("R", "size"), up=("d_b_mixed", lambda v: int((v > 0).sum())), d_b_mixed=("d_b_mixed", "median"),
        R=("R", "median"), absorbed_b=("absorbed_b", "median"), absorbed_a=("absorbed_a", "median")).reset_index()
    per_m.to_csv(os.path.join(args.out, "per_m.csv"), index=False)

    cells = []
    for (K, arch, rho), g in per_m.groupby(["K", "arch", "rho"]):
        g = g.sort_values("m")
        m_star = crossing(g.m.to_numpy(), g.d_b_mixed.to_numpy())
        pos = g[g.R > 0]
        slope = float(np.polyfit(logit(pos.m), np.log(pos.R), 1)[0])
        above = g[g.absorbed_b > 0.5]
        at = g[np.isclose(g.m, 1 / K, atol=1e-3)].iloc[0]
        cells.append(dict(K=K, arch=arch, rho=rho, **{"1/K": 1 / K, "tasks up at 1/K": f"{at.up}/{at.tasks}",
                          "R at 1/K": at.R}, m_star=m_star, excess=m_star - 1 / K, slope=slope,
                          absorption_from=float(above.m.min()) if len(above) else np.nan))
    t = pd.DataFrame(cells)
    t.to_csv(os.path.join(args.out, "cells.csv"), index=False)

    p1 = int((t["tasks up at 1/K"].str.split("/").str[0].astype(int) >= 9).sum())
    p2 = int(t.slope.between(0.8, 1.2).sum())
    k3 = t[t.K == 3]
    lin05 = k3[(k3.arch == "linear") & (k3.rho == 0.5)].m_star.iloc[0]
    others = k3[~((k3.arch == "linear") & (k3.rho == 0.5))].m_star
    order = t.pivot_table(index=["K", "arch"], columns="rho", values="excess")
    p4 = int((order[0.9] < order[0.5]).sum())
    p5 = int(((t.absorption_from >= t.m_star - 1e-9) | t.absorption_from.isna()).sum())
    lines = ["# Findings: v3e, T15 threshold in class share (PREREG_v3d addendum 1, exploratory)", "",
             f"Generated by `extra/experiments/analyze_v3e.py` from {len(runs)} runs (SGD, η = 0.01, exact expected update, "
             "uniform start). m*: where the median one-step change of class B under the actual update crosses zero. "
             "`absorption_from`: smallest grid m with median minority absorption above 0.5 at 10,000 steps.", "",
             markdown(t), "",
             f"1. **m\\* strictly above 1/K** (class B gains at m = 1/K in ≥ 9 of 10 tasks): {p1} of {len(t)} cells.",
             f"2. **Odds scaling** (slope of log R on logit m within 0.8–1.2): {p2} of {len(t)} cells "
             f"(range {t.slope.min():.2f}–{t.slope.max():.2f}).",
             f"3. **Location for K = 3:** linear, ρ = 0.5: m\\* = {lin05:.3f} (predicted 0.37–0.42); the other three "
             f"cells: {', '.join(f'{v:.3f}' for v in others)} (predicted 0.34–0.37).",
             f"4. **m\\* − 1/K smaller at ρ = 0.9 than at ρ = 0.5:** {p4} of {len(order)} (K, architecture) pairs.",
             f"5. **Absorption only at or above m\\*:** {p5} of {len(t)} cells.", "",
             "## Per m", "", markdown(per_m), ""]
    with open(os.path.join(args.out, "FINDINGS.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:16]))


if __name__ == "__main__":
    main()
