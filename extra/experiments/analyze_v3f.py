"""
Analysis of v3f (T16: pass@k rules at matched progress), implementing PREREG_v3d_addendum2.md.

usage:
    python extra/experiments/analyze_v3f.py [--raw ~/rlvr-data/v3f] [--out extra/analysis/v3f]

Matched point: the first logged step at which the majority class mean reaches 0.80.
"""

import argparse
import glob
import gzip
import json
import os
import sys
from multiprocessing import Pool

import numpy as np
import pandas as pd

sys.path[:0] = [os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),  # repo root
                 os.path.dirname(os.path.dirname(os.path.abspath(__file__)))]  # extra/

from experiments.analyze import markdown  # noqa: E402
from experiments.analyze_v3 import t1_labels  # noqa: E402

TAU, TARGET = 1e-3, 0.80


def read_one(path):
    with gzip.open(path, "rt") as f:
        d = json.load(f)
    cfg = d["config"]
    steps = np.array([h["step"] for h in d["history"]])
    means = np.array([h["class_mean"] for h in d["history"]])
    hit = np.nonzero(means[:, 0] >= TARGET)[0]
    cls, _ = t1_labels(cfg)
    absorbed = (np.asarray(d["tail_max"]) < TAU) & (np.asarray(d["p_init"]) >= 10 * TAU)
    return dict(rule=cfg["rule"] if cfg.get("passk") is None else f"{cfg['rule']}{cfg['passk']}", k=cfg.get("passk") or 1,
                family=cfg["rule"], G=cfg["G"], eta=cfg["eta"], task_seed=cfg["task_seed"],
                reached=bool(len(hit)), matched_step=int(steps[hit[0]]) if len(hit) else -1,
                minority_at_match=float(means[hit[0], 1]) if len(hit) else np.nan,
                majority_final=float(means[-1, 0]), minority_final=float(means[-1, 1]),
                minority_absorbed=float(absorbed[cls != 0].mean()))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw", default=os.path.expanduser("~/rlvr-data/v3f"))
    parser.add_argument("--out", default="extra/analysis/v3f")
    args = parser.parse_args()
    paths = sorted(glob.glob(os.path.join(args.raw, "*", "results", "*", "*.json.gz")))
    with Pool(8) as pool:
        runs = pd.DataFrame(pool.map(read_one, paths, chunksize=8))
    os.makedirs(args.out, exist_ok=True)
    runs.to_csv(os.path.join(args.out, "runs.csv"), index=False)

    cells = runs.groupby(["rule", "G", "eta"]).apply(lambda g: pd.Series({
        "reached 0.80": f"{int(g.reached.sum())}/{len(g)}",
        "matched step (median)": float(g.matched_step[g.reached].median()) if g.reached.any() else np.nan,
        "minority at match (median)": float(g.minority_at_match.median()),
        "above 0.2 at match": f"{int((g.minority_at_match > 0.2).sum())}/{int(g.reached.sum())}",
        "below 0.01 at match": f"{int((g.minority_at_match < 0.01).sum())}/{int(g.reached.sum())}",
        "majority final": float(g.majority_final.median()), "minority final": float(g.minority_final.median()),
        "minority absorbed": float(g.minority_absorbed.mean())})).reset_index()
    cells.to_csv(os.path.join(args.out, "cells.csv"), index=False)

    pk = runs[runs.family.isin(["passk", "rloo_k"])]
    ok1 = pk.groupby(["rule", "G", "eta"]).apply(
        lambda g: g.reached.sum() > 0 and (g.minority_at_match[g.reached] > 0.2).sum() >= 0.9 * g.reached.sum())
    grpo = runs[runs.rule == "grpo"].groupby(["G", "eta"]).apply(
        lambda g: g.reached.sum() > 0 and (g.minority_at_match[g.reached] < 0.01).sum() >= 0.9 * g.reached.sum())
    big = pk[(pk.k >= 4) & (pk.eta == 1)].groupby(["rule", "G"]).apply(
        lambda g: pd.Series({"reached": int(g.reached.sum()), "runs": len(g), "absorbed": float(g.minority_absorbed.max())}))
    ok2 = int(((big.reached >= 0.9 * big.runs) & (big.absorbed == 0)).sum())
    med = pk[pk.reached].groupby(["family", "G", "eta", "k"]).matched_step.median().unstack("k")
    ok3 = int(((med[2] < med[4]) & (med[4] < med[8])).sum())
    lines = ["# Findings: v3f, T16 pass@k rules at matched progress (PREREG_v3d addendum 2, exploratory)", "",
             f"Generated by `extra/experiments/analyze_v3f.py` from {len(runs)} runs (minority task: linear, ρ = 0.9, m = 0.9; "
             "sampled updates; 20,000 steps). Matched point: the first logged step where the majority class mean "
             "reaches 0.80.", "", markdown(cells), "",
             f"1. **Protection at matched progress** (minority mean above 0.2 at the matched point in ≥ 90% of the runs "
             f"that reach it): {int(ok1.sum())} of {len(ok1)} pass@k cells. grpo below 0.01 there: {int(grpo.sum())} of {len(grpo)} cells.",
             f"2. **Not just slow** (k = 4 and 8 at η = 1: the majority reaches 0.80 in ≥ 9 of 10 tasks and no minority "
             f"prompt is absorbed): {ok2} of {len(big)} (rule, G) cells.",
             f"3. **Cost** (the matched point comes later as k grows, k = 2 < 4 < 8): {ok3} of {len(med)} (rule family, G, η) cells.",
             "", "Median step to reach the matched point, by k:", "", markdown(med.reset_index()), ""]
    with open(os.path.join(args.out, "FINDINGS.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[-9:]))
    print(cells[cells.eta == 1].to_string(index=False))


if __name__ == "__main__":
    main()
