"""
Analysis of v3n (T26: shared skills), implementing PREREG_v3d_addendum8.md.

usage:
    python extra/experiments/analyze_v3n.py [--raw ~/rlvr-data/v3n] [--out extra/analysis/v3n]

Four-token answers: positions 0..k-1 carry the answer class, positions k..3 a balanced rule shared by all
prompts. At a uniform start the overlap of prompts x and y is k(x, y) * S(x, y), S = sum_l (delta_l - 1/K),
delta_l = 1 if their correct tokens agree at position l. The predicted step-0 push ratio is
R = -sum_{y in B, x in A} k S / sum_{y in B, x in B} k S, with no fitted constant.
"""

import argparse
import glob
import gzip
import json
import os
import sys
from multiprocessing import Pool

import numpy as np
import pandas as pd
import torch

sys.path[:0] = [os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),  # repo root
                 os.path.dirname(os.path.dirname(os.path.abspath(__file__)))]  # extra/

from experiments.analyze import markdown  # noqa: E402
from experiments.run import DEFAULTS, build  # noqa: E402

KS = [1, 2, 3, 4]


def predicted_ratio(cfg):
    _, train, _, policy = build(dict(DEFAULTS, **cfg))
    x = torch.as_tensor(train[0], dtype=torch.float64)
    with torch.no_grad():
        phi = policy.features(x).double().numpy()
    if policy.output.bias is not None:
        phi = np.concatenate([phi, np.ones((len(phi), 1))], axis=1)
    c = train[1]
    K = cfg["K"]
    a = c[:, 0] == 0
    S = (c[:, None, :] == c[None, :, :]).sum(axis=-1) - c.shape[1] / K
    kS = (phi @ phi.T) * S
    cross, own = kS[np.ix_(~a, a)].sum(), kS[np.ix_(~a, ~a)].sum()
    return dict(pred_R=float(-cross / own), cross_sum=float(cross), own_sum=float(own))


def read_one(path):
    with gzip.open(path, "rt") as f:
        d = json.load(f)
    cfg = d["config"]
    small = {k: v for k, v in cfg.items() if (k in DEFAULTS or k == "task_seed") and not k.startswith("_")}
    _, train, _, _ = build(dict(DEFAULTS, **small))
    cls = train[1][:, 0]
    p0, tail = np.asarray(d["p_init"]), np.asarray(d["tail_max"])
    means = np.array([h["class_mean"] for h in d["history"]])
    row = dict(arch=cfg["arch"], rho=cfg["rho"], m=cfg["majority"], k=cfg["differing_positions"],
               task_seed=cfg["task_seed"],
               absorbed=float(((tail < 1e-3) & (p0 >= 1e-2))[cls != 0].mean()),
               majority_absorbed=float(((tail < 1e-3) & (p0 >= 1e-2))[cls == 0].mean()),
               minority_lowest=float(means[:, 1].min()), minority_final=float(means[-1, 1]),
               majority_final=float(means[-1, 0]))
    for step, b in d["branches"].items():
        tag = {"0": "0", "999": "10", "1000": "10", "4999": "50", "5000": "50"}.get(step, step)
        row[f"d_b_a_{tag}"] = b["d_b_a"]
        row[f"d_b_b_{tag}"] = b["d_b_b"]
    row["R"] = -row["d_b_a_0"] / row["d_b_b_0"]
    row.update(predicted_ratio(small))
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=os.path.expanduser("~/rlvr-data/v3n"))
    ap.add_argument("--out", default="extra/analysis/v3n")
    a = ap.parse_args()
    paths = sorted(glob.glob(os.path.join(a.raw, "*", "results", "*", "*.json.gz")))
    with Pool(4) as pool:
        runs = pd.DataFrame(pool.map(read_one, paths, chunksize=4))
    os.makedirs(a.out, exist_ok=True)
    runs.to_csv(os.path.join(a.out, "runs.csv"), index=False)
    runs["rel_err"] = np.abs(runs.R / runs.pred_R - 1)
    p1 = float((runs.rel_err <= 0.05).mean())
    pos = runs[runs.cross_sum > 0]
    p2 = int((pos.d_b_a_0 > 0).sum())
    keys = ["arch", "rho", "m"]
    cells = runs.groupby(keys + ["k"]).agg(
        tasks=("task_seed", "size"), pred_R=("pred_R", "median"), R=("R", "median"),
        absorbed=("absorbed", "mean"), low=("absorbed", lambda v: int((v <= 0.10).sum())),
        minority_lowest=("minority_lowest", "median"), minority_final=("minority_final", "median"),
        majority_final=("majority_final", "median"),
        help0=("d_b_a_0", lambda v: int((v > 0).sum())), help10=("d_b_a_10", lambda v: int((v > 0).sum())),
        help50=("d_b_a_50", lambda v: int((v > 0).sum()))).reset_index()
    cells.to_csv(os.path.join(a.out, "cells.csv"), index=False)
    wide = cells.pivot_table(index=keys, columns="k", values="absorbed")[KS]
    mono = (wide.diff(axis=1).iloc[:, 1:] >= 0).all(axis=1)          # absorbed rises with k
    k1 = cells[cells.k == 1].set_index(keys)["low"] >= 9
    show = lambda v: markdown(cells.pivot_table(index=keys, columns="k", values=v)[KS].reset_index())  # noqa: E731
    lines = ["# Findings: v3n, T26 shared skills (PREREG_v3d addendum 8, exploratory)", "",
             f"Generated by `extra/experiments/analyze_v3n.py` from {len(runs)} runs (L = 4, K = 3, SGD η = 0.1, "
             "10,000 steps; k = positions carrying the answer class, 4 − k shared positions).", "",
             f"1. **Step-0 push ratio within 5% of the computed value** (≥ 95% of tasks): {p1:.3f} of {len(runs)} "
             f"(median relative error {runs.rel_err.median():.4f}; linear {runs[runs.arch == 'linear'].rel_err.median():.4f}, "
             f"MLP {runs[runs.arch == 'mlp'].rel_err.median():.4f}).",
             f"2. **Where the computed majority–minority sum is positive, the majority-only step raises the minority** "
             f"(all such tasks): {p2} of {len(pos)}.",
             f"3. **Absorption falls as sharing grows** (non-decreasing in k, every cell): {int(mono.sum())} of {len(mono)} cells; "
             f"**at k = 1 at most 10% absorbed in ≥ 9 of 10 tasks**: {int(k1.sum())} of {len(k1)} cells.",
             "4. **Does the majority still help later?** Tasks (of 10) whose majority-only step raises the minority, "
             "at step 0, 10% and 50% of training: see the tables below.", "",
             "## Predicted push ratio R (median)", "", show("pred_R"), "",
             "## Measured push ratio R (median)", "", show("R"), "",
             "## Minority prompts absorbed at 1e-3 (mean share)", "", show("absorbed"), "",
             "## Minority's lowest class mean (median)", "", show("minority_lowest"), "",
             "## Minority at the end (median)", "", show("minority_final"), "",
             "## Majority at the end (median)", "", show("majority_final"), "",
             "## Tasks where the majority-only step raises the minority: step 0", "", show("help0"), "",
             "## ... at 10% of training", "", show("help10"), "", "## ... at 50% of training", "", show("help50"), ""]
    with open(os.path.join(a.out, "FINDINGS.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
