"""
Analysis of v3i (T21: prevention levers in the enumerable transformer environment), implementing
PREREG_T20_addendum1.md.

usage:
    python extra/experiments/analyze_v3i.py [--raw ~/rlvr-data/v3i] [--out extra/analysis/v3i]

A cell is one task x update x step rule. Collapsing cells: the no-lever arm has a mean absorbed share >= 0.5.
"""

import argparse
import glob
import gzip
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path[:0] = [os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),  # repo root
                 os.path.dirname(os.path.dirname(os.path.abspath(__file__)))]  # extra/

from experiments.analyze import markdown  # noqa: E402

TAU = 1e-3


def read_one(path):
    with gzip.open(path, "rt") as f:
        d = json.load(f)
    cfg = d["config"]
    cls, p0, tail = np.asarray(d["cls"]), np.asarray(d["p_init"]), np.asarray(d["tail_max"])
    absorbed = (tail < TAU) & (p0 >= 10 * TAU)
    if cfg.get("enum_passk"):
        arm = f"pass@{cfg['enum_passk']}"
    elif cfg.get("enum_beta"):
        arm = f"{cfg['enum_kl']} KL {cfg['enum_beta']:g}"
    else:
        arm = "none"
    means = np.array([h["class_mean"] for h in d["history"]])
    steps = np.array([h["step"] for h in d["history"]])
    hit = np.nonzero(means[:, 0] >= 0.8)[0]
    return dict(task="parity 48/64" if cfg["partition"] == "parity" else f"K={cfg['K']} {cfg['n_major']}/64",
                update="exact" if cfg["algo"] == "pg" else "sampled", stepper=f"{cfg['optimizer']} {cfg['eta']:g}",
                arm=arm, seed=cfg["seed"], absorbed_b=float(absorbed[cls != 0].mean()),
                absorbed_a=float(absorbed[cls == 0].mean()), majority_final=float(means[-1, 0]),
                minority_final=float(means[-1, 1]), minority_lowest=float(means[:, 1].min()),
                matched_step=int(steps[hit[0]]) if len(hit) else -1,
                minority_at_match=float(means[hit[0], 1]) if len(hit) else np.nan)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw", default=os.path.expanduser("~/rlvr-data/v3i"))
    parser.add_argument("--out", default="extra/analysis/v3i")
    args = parser.parse_args()
    runs = pd.DataFrame([read_one(p) for p in sorted(glob.glob(os.path.join(args.raw, "*", "results", "*", "*.json.gz")))])
    os.makedirs(args.out, exist_ok=True)
    runs.to_csv(os.path.join(args.out, "runs.csv"), index=False)
    keys = ["task", "update", "stepper"]
    cells = runs.groupby(keys + ["arm"]).agg(
        seeds=("seed", "size"), absorbed=("absorbed_b", "mean"), majority_absorbed=("absorbed_a", "mean"),
        majority_final=("majority_final", "median"), minority_final=("minority_final", "median"),
        minority_lowest=("minority_lowest", "median"), reached=("matched_step", lambda v: int((v >= 0).sum())),
        matched_step=("matched_step", lambda v: float(v[v >= 0].median()) if (v >= 0).any() else np.nan),
        minority_at_match=("minority_at_match", "median")).reset_index()
    cells.to_csv(os.path.join(args.out, "cells.csv"), index=False)
    wide = cells.pivot_table(index=keys, columns="arm", values="absorbed")
    final = cells.pivot_table(index=keys, columns="arm", values="majority_final")
    collapsing = wide["none"] >= 0.5
    p1 = (wide[["forward KL 0.03", "forward KL 0.3"]] <= 0.05).all(axis=1)
    p2 = final["forward KL 0.03"] >= 0.8
    p3 = wide.loc[collapsing, "reverse KL 0.03"] >= 0.5
    p4 = (wide.loc[collapsing, "none"] - wide.loc[collapsing, "pass@4"]) >= 0.3
    order = ["none", "reverse KL 0.03", "reverse KL 0.3", "forward KL 0.03", "forward KL 0.3", "pass@2", "pass@4"]
    table = lambda value: markdown(cells.pivot_table(index=keys, columns="arm", values=value)[order].reset_index())  # noqa: E731
    lines = ["# Findings: v3i, T21 prevention levers in the transformer environment (PREREG_T20 addendum 1, exploratory)", "",
             f"Generated by `extra/experiments/analyze_v3i.py` from {len(runs)} runs (shared transformer, 2,000 steps, 10 seeds). "
             f"Collapsing cells (no-lever arm absorbs at least half of the minority): {int(collapsing.sum())} of {len(wide)}.", "",
             f"1. **Forward KL prevents absorption** (mean absorbed share ≤ 0.05 at both β): {int(p1.sum())} of {len(p1)} cells.",
             f"2. **Forward KL at β = 0.03 costs little** (class 0 ends at ≥ 0.8): {int(p2.sum())} of {len(p2)} cells.",
             f"3. **Reverse KL at β = 0.03 does not prevent it** (absorbed ≥ 0.5): {int(p3.sum())} of {len(p3)} collapsing cells.",
             f"4. **pass@4 lowers absorption by at least 0.3:** {int(p4.sum())} of {len(p4)} collapsing cells.", "",
             "## Minority prompts absorbed (mean share)", "", table("absorbed"), "",
             "## Class 0 at the end (median)", "", table("majority_final"), "",
             "## Minority at the end (median)", "", table("minority_final"), "",
             "## Minority's lowest class mean during training (median)", "", table("minority_lowest"), "",
             "## Class 0 absorbed (mean share)", "", table("majority_absorbed"), ""]
    with open(os.path.join(args.out, "FINDINGS.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
