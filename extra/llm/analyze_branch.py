"""
C10 analysis (who pushes whom in the LLM), as pre-registered in PREREG_C10.md.

usage:
    python extra/llm/analyze_branch.py --problems extra/llm/pools/c2/all.json --heldout extra/llm/pools/c2/heldout_ids.json \\
        --base0 <c2 base seed 0> --base1 <c2 base seed 1> --runs <run dirs...> --out extra/analysis/llm/c10.md

A run dir holds run/config.json, step50.json.gz and after_n128.json.gz. Its role (the majority procedure) and
arm (mixed, majority_only, minority_only) are read from the --strata of its config. Changes are in mean
success over the 300 held-out problems of a procedure, against the base model (seed 0).
"""

import argparse
import gzip
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path[:0] = [os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),  # repo root
                 os.path.dirname(os.path.dirname(os.path.abspath(__file__)))]  # extra/

from llm.analyze_c0 import markdown  # noqa: E402

OTHER = {"each": "total", "total": "each"}
STEPS = {"step50.json.gz": 50, "after_n128.json.gz": 100}


def read(path):
    with gzip.open(path, "rt") as f:
        return json.load(f)


def describe(path):
    """(role, arm, seed): role is the majority procedure; the minority gets at most 4 prompts per step."""
    cfg = json.load(open(os.path.join(path, "run", "config.json")))
    counts = {k: int(v) for k, v in (item.split("=") for item in cfg["strata"].split(":", 1)[1].split(","))}
    a, b = sorted(counts, key=counts.get)                     # a has the smaller count
    if counts[a] > 0:
        return dict(role=b, arm="mixed", seed=cfg["seed"])
    if counts[b] <= 4:
        return dict(role=a, arm="minority_only", seed=cfg["seed"])
    return dict(role=b, arm="majority_only", seed=cfg["seed"])


def rates(counts, ids):
    return np.array([counts[i][0] / counts[i][2] for i in ids])


def boot_ci(x, rng, draws=2000):
    means = x[rng.integers(len(x), size=(draws, len(x)))].mean(axis=1)
    return float(np.quantile(means, 0.025)), float(np.quantile(means, 0.975))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--problems", required=True)
    parser.add_argument("--heldout", required=True)
    parser.add_argument("--base0", required=True)
    parser.add_argument("--base1", required=True)
    parser.add_argument("--runs", nargs="+", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    problems = {q["id"]: q for q in json.load(open(args.problems))}
    held = json.load(open(args.heldout))
    panel = {proc: [i for i in held if problems[i]["procedure"] == proc] for proc in OTHER}
    b0, b1 = read(args.base0)["counts"], read(args.base1)["counts"]
    rng = np.random.default_rng(0)
    null = {proc: float((rates(b1, ids) - rates(b0, ids)).mean()) for proc, ids in panel.items()}

    rows = []
    for path in args.runs:
        info = describe(path)
        minority = OTHER[info["role"]]
        for name, step in STEPS.items():
            f = os.path.join(path, name)
            if not os.path.exists(f):
                continue
            c = read(f)["counts"]
            d_min = rates(c, panel[minority]) - rates(b0, panel[minority])
            d_maj = rates(c, panel[info["role"]]) - rates(b0, panel[info["role"]])
            lo, hi = boot_ci(d_min, rng)
            rows.append(dict(info, step=step, d_minority=float(d_min.mean()), lo=lo, hi=hi, d_majority=float(d_maj.mean()),
                             null_minority=null[minority]))
    runs = pd.DataFrame(rows).sort_values(["role", "step", "arm", "seed"])

    lines = ["# C10: who pushes whom in the LLM", "",
             "Generated by `extra/llm/analyze_branch.py`; tests as pre-registered in `PREREG_C10.md`. Changes are in mean "
             "success on the 300 held-out problems of a procedure, against the base model (seed 0). The interval is a "
             "problem-level bootstrap. Null: base seed 1 minus base seed 0 on the same panel.", "",
             "| Panel | Null change |", "|---|---|"] + [f"| {p} | {v:+.4f} |" for p, v in null.items()] + [""]
    lines += ["## Every run", "", markdown(runs), ""]

    cells = runs.groupby(["role", "step", "arm"]).agg(
        runs=("seed", "size"), d_minority=("d_minority", "mean"), d_majority=("d_majority", "mean"),
        negative=("hi", lambda v: int((v < 0).sum())), positive=("lo", lambda v: int((v > 0).sum()))).reset_index()
    lines += ["## By arm (mean over seeds; negative / positive: runs whose interval excludes zero)", "", markdown(cells), ""]

    lines += ["## Predictions (step 100)", ""]
    final = cells[cells.step == 100].set_index(["role", "arm"])
    ok = {1: [], 2: [], 3: []}
    for role in OTHER:
        if not all((role, arm) in final.index for arm in ("mixed", "majority_only", "minority_only")):
            lines.append(f"- majority `{role}`: runs missing; not tested.")
            continue
        a, b, mixed = (final.loc[(role, arm)] for arm in ("majority_only", "minority_only", "mixed"))
        ok[1].append(bool(a.negative == a.runs))
        ok[2].append(bool(b.positive == b.runs))
        gap = abs(mixed.d_minority - (a.d_minority + b.d_minority))
        ok[3].append(bool(gap <= 0.5 * max(abs(a.d_minority), abs(b.d_minority))))
        ratio = -a.d_minority / b.d_minority if b.d_minority else float("nan")
        lines.append(f"- majority `{role}` (minority `{OTHER[role]}`): majority-only {a.d_minority:+.4f} "
                     f"({int(a.negative)}/{int(a.runs)} runs below zero), minority-only {b.d_minority:+.4f} "
                     f"({int(b.positive)}/{int(b.runs)} above zero), mixed {mixed.d_minority:+.4f} against the sum "
                     f"{a.d_minority + b.d_minority:+.4f}; R = {ratio:.2f}.")
    verdict = lambda v: "not tested" if len(v) < 2 else ("HOLDS" if all(v) else "FAILS")  # noqa: E731
    lines += ["", f"1. **Majority-only steps lower the minority** (every run, both roles): {verdict(ok[1])}.",
              f"2. **Minority-only steps raise it** (every run, both roles): {verdict(ok[2])}.",
              f"3. **The mixed change is close to the sum** (within half of the larger part, both roles): {verdict(ok[3])}.", ""]
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    runs.to_csv(args.out.replace(".md", "_runs.csv"), index=False)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
