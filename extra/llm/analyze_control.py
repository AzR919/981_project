"""
C1 held-out control (PREREG_C1_amendment2.md): are the held-out declines specific to GRPO?

usage:
    python extra/llm/analyze_control.py --base0 b0.json.gz --base1 b1.json.gz --train-ids extra/llm/pools/qwen_c1_train.json \\
        --heldout-ids extra/llm/pools/qwen_c1_heldout.json --grpo dir1 dir2 dir3 --control dir1 dir2 dir3 --out c1_control.md

Each run dir holds after_n256.json.gz. Declines: one-sided Fisher exact test against the base model (seed 0) with
Benjamini-Hochberg at 10%, separately on the training and the held-out problems; lost: a decline ending at
success <= 0.05; gains: the same test in the other direction.
"""

import argparse
import gzip
import json
import os
import sys

import pandas as pd

sys.path[:0] = [os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),  # repo root
                 os.path.dirname(os.path.dirname(os.path.abspath(__file__)))]  # extra/

from llm.analyze_c0 import markdown  # noqa: E402
from llm.declines import compare  # noqa: E402


def counts(path):
    with gzip.open(path, "rt") as f:
        return json.load(f)["counts"]


def row(arm, name, base, after, sets):
    out = {"arm": arm, "run": name}
    for label, ids in sets:
        down = compare({i: base[i] for i in ids}, {i: after[i] for i in ids}, 0.1)
        up = compare({i: after[i] for i in ids}, {i: base[i] for i in ids}, 0.1)
        out.update({f"{label} before": float(down.p_before.mean()), f"{label} after": float(down.p_after.mean()),
                    f"{label} declines": int(down.decline.sum()), f"{label} lost": int(down.lost.sum()),
                    f"{label} gains": int(up.decline.sum())})
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--base0", required=True)
    parser.add_argument("--base1", required=True)
    parser.add_argument("--train-ids", required=True)
    parser.add_argument("--heldout-ids", required=True)
    parser.add_argument("--grpo", nargs="+", required=True)
    parser.add_argument("--control", nargs="+", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    base = counts(args.base0)
    sets = [("train", json.load(open(args.train_ids))), ("held-out", json.load(open(args.heldout_ids)))]
    rows = [row("null", "base seed 1", base, counts(args.base1), sets)]
    for arm, dirs in (("GRPO", args.grpo), ("control", args.control)):
        for d in dirs:
            name = os.path.basename(os.path.dirname(d.rstrip("/"))) + "/" + os.path.basename(d.rstrip("/"))
            rows.append(row(arm, name, base, counts(os.path.join(d, "after_n256.json.gz")), sets))
    table = pd.DataFrame(rows)
    grpo, control = table[table.arm == "GRPO"], table[table.arm == "control"]
    d_control, d_grpo = control["held-out declines"].tolist(), grpo["held-out declines"].tolist()
    if all(d <= 4 for d in d_control):
        verdict = "specific to GRPO by the registered count rule (every control run has at most 4 held-out declines)"
    elif sum(d >= 8 for d in d_control) >= 2:
        verdict = "generic to fine-tuning by the registered count rule (at least two control runs have 8 or more)"
    else:
        verdict = "undecided by the registered count rule"
    weak = control["train after"].mean() < 0.75
    lines = ["# C1 held-out control: rejection-sampling fine-tuning against GRPO", "",
             "Generated by `extra/llm/analyze_control.py`; rule as pre-registered in `PREREG_C1_amendment2.md`.", "",
             markdown(table), "",
             f"- Held-out declines: GRPO {d_grpo}; control {d_control}.",
             f"- **Verdict: {verdict}.**",
             f"- Training success after: GRPO {grpo['train after'].mean():.2f}, control {control['train after'].mean():.2f}. "
             + ("**The control's training effect is below the registered 0.75, so the comparison is confounded by a "
                "smaller training effect.**" if weak else "The control's training effect meets the registered 0.75."), ""]
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    table.to_csv(args.out.replace(".md", "_runs.csv"), index=False)
    print("\n".join(lines[-4:]))


if __name__ == "__main__":
    main()
