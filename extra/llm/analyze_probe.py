"""
Summarise the model probes (llm/jobs/probe_*.txt) into one measured table.

usage:
    python llm/analyze_probe.py results/llm/q_* --out analysis/llm/model_probe.md

Per probe dir: probe.txt (model, mode), gpumem_{base,train}.txt (nvidia-smi MiB
every 0.5 s), base.json.gz / base_int8.json.gz / after.json.gz (64 problems x 8),
run/log.jsonl (5 GRPO steps with sync checks). GPU-hours for one C1 arm are
projected from the measured rates: calibration (2 x 3,000 x 32 base samples,
4 pilots x 150 steps, 2 x 1,300 x 256 base samples) plus 3 seeds x (500 steps +
1,300 x 256 samples).
"""

import argparse
import gzip
import json
import os

import numpy as np


def peak(path):
    if not os.path.exists(path):
        return np.nan
    vals = [int(v) for v in open(path).read().split() if v.strip().isdigit()]
    return max(vals) / 1024 if vals else np.nan


def evaluation(path):
    if not os.path.exists(path):
        return None
    d = json.load(gzip.open(path, "rt"))
    c = np.array(list(d["counts"].values()))
    return dict(p=c[:, 0].sum() / c[:, 2].sum(), fmt=1 - c[:, 1].sum() / c[:, 2].sum(),
                tok_s=d["tokens_per_second"], tok_per=d["tokens"] / c[:, 2].sum())


def row(d):
    model, mode = open(os.path.join(d, "probe.txt")).read().split()
    out = dict(model=model.split("/")[-1], mode=mode, status="DONE" if os.path.exists(os.path.join(d, "DONE"))
               else "FAILED" if os.path.exists(os.path.join(d, "FAILED")) else "running")
    base, after = evaluation(os.path.join(d, "base.json.gz")), evaluation(os.path.join(d, "after.json.gz"))
    int8 = evaluation(os.path.join(d, "base_int8.json.gz"))
    log_path = os.path.join(d, "run", "log.jsonl")
    log = [json.loads(line) for line in open(log_path)] if os.path.exists(log_path) else []
    out.update(gpu_eval_gb=peak(os.path.join(d, "gpumem_base.txt")), gpu_train_gb=peak(os.path.join(d, "gpumem_train.txt")),
               torch_peak_gb=max((r["peak_gb"] for r in log), default=np.nan),
               s_per_step=np.mean([r["t_step"] for r in log[1:]]) if len(log) > 1 else np.nan,
               base_p=base["p"] if base else np.nan, base_fmt_fail=base["fmt"] if base else np.nan,
               int8_base_p=int8["p"] if int8 else np.nan, after_p=after["p"] if after else np.nan,
               eval_tok_s=base["tok_s"] if base else np.nan)
    gaps = [abs(r["sync_check"]["vllm_logp"] - r["sync_check"]["policy_logp"]) for r in log if "sync_check" in r]
    out["sync_gap_nats"] = max(gaps) if gaps else np.nan
    if base and len(log) > 1:
        eval_s = lambda samples: samples * base["tok_per"] / base["tok_s"]  # noqa: E731
        hours = (2 * eval_s(3000 * 32) + 4 * 150 * out["s_per_step"] + 2 * eval_s(1300 * 256)
                 + 3 * (500 * out["s_per_step"] + eval_s(1300 * 256))) / 3600
        out["gpu_h_per_arm"] = hours
    else:
        out["gpu_h_per_arm"] = np.nan
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("dirs", nargs="+")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    rows = []
    for d in args.dirs:
        for sub in sorted(os.listdir(d)) if os.path.isdir(d) else []:
            path = os.path.join(d, sub)
            if os.path.exists(os.path.join(path, "probe.txt")):
                rows.append(row(path))
    if not rows:
        raise SystemExit("no probe dirs found")
    cols = list(rows[0])
    lines = ["# Model probes: measured memory, speed, sync gap and difficulty on one RTX 4090", "",
             "Generated by `llm/analyze_probe.py`. Memory in GB (nvidia-smi peak, whole GPU); p̂ on the first "
             "64 GSM8K train problems × 8 samples; sync gap = largest |vLLM − policy| log-prob of one 64-token "
             "answer over the first syncs (bf16 runs: ~0.1–0.4 nats).", "",
             "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join(f"{r[c]:.3g}" if isinstance(r[c], float) else str(r[c]) for c in cols) + " |")
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
