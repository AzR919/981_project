"""
C7/C8 question 2 (NEXT_PLAN, C7): does each problem's end state follow the finite-G KL fixed point?

For each KL run and each training problem: p_ref = the base model's success (two base evaluations pooled,
512 samples), p_after = the run's success after training (256 samples). The prediction p* is the stable root of
the per-prompt fixed-point equation (synthetic_rl.theory.fixed_points) nearest p_ref in the logit, for the run's
G, GRPO and KL direction, at beta_eff = s * beta. One free scale s per run (the per-token KL maps to the toy's
sequence beta only up to a constant), chosen on a log grid to minimise the squared logit error.
Reported: the fitted s, and the slope, R^2 and Spearman of logit p_after against logit p*.

usage: python llm/analyze_kl_fixed_points.py --runs label=dir,... [--runs ...] --base0 F --base1 F --train-ids F --out F
"""

import argparse
import gzip
import json
import os
import sys
from functools import lru_cache

import numpy as np
from scipy.stats import spearmanr

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from synthetic_rl.theory import fixed_points  # noqa: E402

N_AFTER = 256
EPS = 0.5 / N_AFTER


def load_counts(path):
    """Per problem: success rate (counts[id] = [correct, ..., samples])."""
    with gzip.open(path, "rt") as f:
        d = json.load(f)
    return {i: c[0] / c[-1] for i, c in d["counts"].items()}


def logit(p):
    p = np.clip(p, EPS, 1 - EPS)
    return np.log(p / (1 - p))


@lru_cache(maxsize=None)
def p_star(p_ref, beta, G, direction):
    p_ref = min(max(p_ref, 1 / 1024), 1 - 1 / 1024)     # base success 0 or 1 out of 512 samples
    roots = [p for p, stable in fixed_points(p_ref, beta, G, "grpo", direction=direction) if stable]
    if not roots:      # the reward outweighs the KL everywhere on the grid: the flow runs to p = 1
        return 1.0
    return min(roots, key=lambda r: abs(logit(r) - logit(p_ref)))


def run_config(run_dir):
    cfg = json.load(open(os.path.join(run_dir, "run", "config.json")))
    return cfg["G"], cfg["beta"], cfg.get("kl", "reverse")


def analyse(run_dir, ids, p_ref):
    G, beta, direction = run_config(run_dir)
    counts = load_counts(os.path.join(run_dir, "after_n256.json.gz"))
    p_after = np.array([counts[i] for i in ids])
    keys = np.round(p_ref, 6)
    best = None
    for s in np.logspace(-2, 2, 33):
        pred = np.array([p_star(float(k), float(s * beta), G, direction) for k in keys])
        ok = np.isfinite(pred)
        err = np.mean((logit(p_after[ok]) - logit(pred[ok])) ** 2)
        if best is None or err < best[0]:
            best = (err, s, pred)
    err, s, pred = best
    ok = np.isfinite(pred)
    x, y = logit(pred[ok]), logit(p_after[ok])
    slope, intercept = np.polyfit(x, y, 1)
    r2 = 1 - np.sum((y - (slope * x + intercept)) ** 2) / np.sum((y - y.mean()) ** 2)
    ref_r2 = np.corrcoef(logit(p_ref[ok]), y)[0, 1] ** 2
    return dict(G=G, beta=beta, kl=direction, scale=s, rmse_logit=float(np.sqrt(err)), slope=float(slope),
                r2=float(r2), spearman=float(spearmanr(pred[ok], p_after[ok]).statistic), r2_p_ref_only=float(ref_r2),
                p_after=float(p_after.mean()), p_star=float(np.nanmean(pred)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", action="append", required=True, help="label=dir1,dir2")
    ap.add_argument("--base0", required=True)
    ap.add_argument("--base1", required=True)
    ap.add_argument("--train-ids", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    ids = [str(i) for i in json.load(open(a.train_ids))]
    b0, b1 = load_counts(a.base0), load_counts(a.base1)
    p_ref = np.array([(b0[i] + b1[i]) / 2 for i in ids])
    lines = ["# C7/C8 question 2: per-problem end state against the finite-G KL fixed point", "",
             "Generated by `llm/analyze_kl_fixed_points.py`. p_ref = base success (512 samples); p* = stable fixed point",
             "nearest p_ref at β_eff = s·β, one scale s per run fitted on a log grid (0.01–100). Slope, R² and Spearman of",
             "logit p_after on logit p*; `R² (p_ref only)` = the same fit using p_ref itself, the no-theory baseline.", "",
             "| arm | run | G | KL | β | fitted s | slope | R² | R² (p_ref only) | Spearman | mean p_after | mean p* |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for spec in a.runs:
        label, dirs = spec.split("=", 1)
        for d in dirs.split(","):
            r = analyse(d.rstrip("/"), ids, p_ref)
            name = os.path.basename(os.path.dirname(d.rstrip("/")))
            lines.append(f"| {label} | {name} | {r['G']} | {r['kl']} | {r['beta']} | {r['scale']:.3g} | {r['slope']:.2f} | "
                         f"{r['r2']:.2f} | {r['r2_p_ref_only']:.2f} | {r['spearman']:.2f} | {r['p_after']:.3f} | {r['p_star']:.3f} |")
            print(lines[-1], flush=True)
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
