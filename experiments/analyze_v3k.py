"""
Analysis of v3k (T23: class-balanced warm start), implementing PREREG_v3d_addendum5.md.

usage:
    python experiments/analyze_v3k.py [--raw ~/rlvr-data/v3k] [--out analysis/v3k]

Class A is answer class 0 (share m); class B is the rest. Absorbed: tail max of success below the threshold
over the last 20% of steps, among prompts that start at or above ten times it.
"""

import argparse
import glob
import gzip
import json
import os
import sys
from multiprocessing import Pool

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from experiments.analyze import markdown  # noqa: E402
from experiments.run import DEFAULTS, build  # noqa: E402

STARTS = ["uniform", "0.5", "0.7", "0.9"]


def read_one(path):
    with gzip.open(path, "rt") as f:
        d = json.load(f)
    cfg = d["config"]
    small = {k: v for k, v in cfg.items() if (k in DEFAULTS or k == "task_seed") and not k.startswith("_")}
    _, train, _, _ = build(dict(DEFAULTS, **dict(small, init="uniform", p0=None)))
    cls = train[1][:, 0]
    p0, tail = np.asarray(d["p_init"]), np.asarray(d["tail_max"])
    means = np.array([h["class_mean"] for h in d["history"]])
    b = d.get("branches", {}).get("0", {})
    start = d.get("start", {})
    return dict(arch=cfg["arch"], m=cfg["majority"], update=cfg["update"], task_seed=cfg["task_seed"],
                start="uniform" if cfg["init"] == "uniform" else f"{cfg['p0']:g}",
                p_a0=start.get("p_a", np.nan), p_b0=start.get("p_b", np.nan),
                b_on_a0=start.get("b_on_a_answer", np.nan),
                absorbed_3=float(((tail < 1e-3) & (p0 >= 1e-2))[cls != 0].mean()),
                absorbed_2=float(((tail < 1e-2) & (p0 >= 1e-1))[cls != 0].mean()),
                majority_absorbed=float(((tail < 1e-3) & (p0 >= 1e-2))[cls == 0].mean()),
                minority_lowest=float(means[:, 1].min()), minority_final=float(means[-1, 1]),
                majority_final=float(means[-1, 0]), d_b_mixed=b.get("d_b_mixed", np.nan),
                d_b_a=b.get("d_b_a", np.nan), d_b_b=b.get("d_b_b", np.nan))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw", default=os.path.expanduser("~/rlvr-data/v3k"))
    parser.add_argument("--out", default="analysis/v3k")
    args = parser.parse_args()
    paths = sorted(glob.glob(os.path.join(args.raw, "*", "results", "*", "*.json.gz")))
    with Pool(8) as pool:
        runs = pd.DataFrame(pool.map(read_one, paths, chunksize=4))
    os.makedirs(args.out, exist_ok=True)
    runs.to_csv(os.path.join(args.out, "runs.csv"), index=False)
    keys = ["arch", "update", "m"]
    cells = runs.groupby(keys + ["start"]).agg(
        tasks=("task_seed", "size"), p_a0=("p_a0", "median"), p_b0=("p_b0", "median"), b_on_a0=("b_on_a0", "median"),
        absorbed=("absorbed_3", "mean"), absorbed_1e2=("absorbed_2", "mean"),
        none=("absorbed_3", lambda v: int((v == 0).sum())), majority_absorbed=("majority_absorbed", "mean"),
        minority_lowest=("minority_lowest", "median"), minority_final=("minority_final", "median"),
        majority_final=("majority_final", "median"),
        first_step_down=("d_b_mixed", lambda v: int((v < 0).sum()) if v.notna().any() else -1)).reset_index()
    cells["start"] = pd.Categorical(cells.start, STARTS, ordered=True)
    cells = cells.sort_values(keys + ["start"])
    cells.to_csv(os.path.join(args.out, "cells.csv"), index=False)

    exact9 = cells[(cells["update"] == "expected_full") & (cells.m == 0.9) & (cells.start != "uniform")]
    p1 = exact9.first_step_down >= 9
    wide = cells.pivot_table(index=keys, columns="start", values="absorbed", observed=True)[STARTS]
    p2 = (wide.diff(axis=1).iloc[:, 1:] <= 0.05).all(axis=1)
    top = cells[cells.start == "0.9"]
    p3 = top.none >= 9
    ratio = wide["0.5"] / wide["uniform"].where(wide["uniform"] > 0)
    def reading(row):
        u, h = row["uniform"], row["0.5"]
        if abs(h - u) <= 0.1:
            return "as at a uniform start"
        if u > 0 and h < 0.5 * u:
            return "gone or much reduced"
        return "partial"
    readings = wide.apply(reading, axis=1)
    show = lambda value: markdown(cells.pivot_table(index=keys, columns="start", values=value, observed=True)[STARTS].reset_index())  # noqa: E731
    lines = ["# Findings: v3k, T23 class-balanced warm start (PREREG_v3d addendum 5, exploratory)", "",
             f"Generated by `experiments/analyze_v3k.py` from {len(runs)} runs (K = 3, ρ = 0.9, SGD η = 0.1, 10,000 steps).", "",
             f"1. **The first step still pushes the minority down** (m = 0.9, exact, every warm start, ≥ 9 of 10 tasks): "
             f"{int(p1.sum())} of {len(p1)} cells.",
             f"2. **Absorption does not increase with p0** (non-increasing along uniform, 0.5, 0.7, 0.9; slack 0.05): "
             f"{int(p2.sum())} of {len(p2)} cells.",
             f"3. **At p0 = 0.9 nothing is absorbed** (≥ 9 of 10 tasks): {int(p3.sum())} of {len(p3)} cells.",
             "4. **p0 = 0.5 against the uniform start** (reading fixed in advance): "
             + "; ".join(f"{a} {u} m={m}: {r}" for (a, u, m), r in readings.items()) + ".", "",
             "## Start values (medians): class A success, class B success, class B's mass on class A's answer", "",
             show("p_a0"), "", show("p_b0"), "", show("b_on_a0"), "",
             "## Minority prompts absorbed at 1e-3 (mean share)", "", show("absorbed"), "",
             "## Minority prompts absorbed at 1e-2 (mean share)", "", show("absorbed_1e2"), "",
             "## Minority's lowest class mean (median)", "", show("minority_lowest"), "",
             "## Minority at the end (median)", "", show("minority_final"), "",
             "## Majority at the end (median)", "", show("majority_final"), "",
             "## Tasks whose first step lowers the minority (exact arm; of 10)", "", show("first_step_down"), ""]
    with open(os.path.join(args.out, "FINDINGS.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:10]))


if __name__ == "__main__":
    main()
